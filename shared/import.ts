type ReadSchema = {
  ok: boolean;
  purpose: string;
  fields: FieldSpec[];
  threshold?: number;
  overrides: Record<string, string>;
  warnings: string[];
};

function readSchema(schema: Json, uiSchema: Json): ReadSchema {
  const warnings: string[] = [];
  const out: ReadSchema = { ok: false, purpose: "", fields: [], overrides: {}, warnings };
  // Zod's own compiler is the cheapest validity check: it rejects contradictory
  // or malformed schemas, and its complaint is useful to show. Best effort only —
  // the mapping below still runs, so a compile failure never blocks an import.
  try {
    const compilable = schema as Parameters<typeof z.fromJSONSchema>[0]; // the same document, parsed from JSON
    z.fromJSONSchema(compilable);
  } catch (e) {
    warnings.push(`Zod cannot compile this schema: ${(e as Error).message.split("\n")[0]}`);
  }
  if (!isObj(schema.properties)) {
    warnings.push('No "properties" found. Paste an object schema, e.g. {"type":"object","properties":{…}}.');
    return out;
  }
  const props = schema.properties;
  const requiredNames = Array.isArray(schema.required) ? schema.required.filter((n): n is string => typeof n === "string") : [];
  out.fields = Object.entries(props).map(([name, prop], i) => normalizeField(mapProperty(name, isObj(prop) ? prop : {}, requiredNames.includes(name), i, warnings)));
  for (const name of requiredNames) if (!(name in props)) warnings.push(`"required" lists "${name}", which is not in properties.`);
  // Ids follow the order the fields are shown in, so a restored form looks like the original.
  out.fields = applyOrder(out.fields, uiSchema[UI_ORDER], warnings).map((f, i) => ({ ...f, id: `imp_${i + 1}` }));
  out.overrides = readOverrides(uiSchema, out.fields, warnings);
  if (!out.fields.length) warnings.push('The "properties" map is empty.');
  out.purpose = typeof schema.description === "string" ? schema.description : typeof schema.title === "string" ? schema.title : "";
  const threshold = finite(schema[X_THRESHOLD]);
  if (threshold !== undefined) out.threshold = clamp01(threshold);
  out.ok = out.fields.length > 0;
  return out;
}

/**
 * One JSON Schema property → a field. KINDS: add new kinds here (time, date-range, range, file).
 * Everything the builder writes is understood, plus the general JSON Schema around it.
 */
function mapProperty(name: string, raw: Json, required: boolean, i: number, warnings: string[]): FieldSpec {
  const { schema: s, emptyAllowed } = unwrapAnyOf(raw, name, warnings);
  // `"type": ["string", "null"]` means the value can be absent.
  const nullable = Array.isArray(s.type) ? s.type.includes("null") : s.type === "null";
  const type = Array.isArray(s.type) ? s.type.find((t) => t !== "null") : s.type;
  const f: FieldSpec = {
    id: `imp_${i + 1}`,
    name,
    // A title is the label, exactly as written; without one, the key is prettified.
    label: typeof s.title === "string" ? s.title : prettify(name),
    kind: "string",
    required: required && !nullable && !emptyAllowed,
  };
  if (typeof s.description === "string" && s.description) f.description = s.description;
  // Verbatim custom Zod code (`x-zod`) and hand-written messages (`errorMessage`) are text we carry along.
  if (typeof s[X_ZOD] === "string" && s[X_ZOD].trim()) f.customZod = s[X_ZOD];
  const messages = readErrorMessages(s.errorMessage);
  if (messages) f.errorMessage = messages;

  // `enum` wins over `type`: JSON Schema writes either, or both.
  if (Array.isArray(s.enum)) {
    if (!s.enum.length) {
      warnings.push(`${name}: the enum is empty — used a text field.`);
      return f;
    }
    f.kind = "enum";
    f.options = s.enum.map(asText);
    if (!s.enum.every((v) => typeof v === "string")) warnings.push(`${name}: non-text enum values were turned into text.`);
    return f;
  }
  if (s.const !== undefined) {
    // `const: true` is how a required boolean ("must be ticked") survives JSON Schema.
    if (typeof s.const === "boolean") {
      f.kind = "boolean";
      if (s.const) f.required = true;
      return f;
    }
    f.kind = "enum";
    f.options = [asText(s.const)];
    return f;
  }

  switch (type) {
    case "string": {
      const format = typeof s.format === "string" ? s.format : undefined;
      if (format === "date" || format === "date-time") {
        f.kind = "date";
        if (format === "date-time") warnings.push(`${name}: date-time is treated as a date (the time is dropped).`);
        if (finite(s.minLength) !== undefined || finite(s.maxLength) !== undefined) warnings.push(`${name}: minLength/maxLength are ignored on a date field.`);
      } else if (format === "time") {
        f.kind = "time";
        if (finite(s.minLength) !== undefined || finite(s.maxLength) !== undefined) warnings.push(`${name}: minLength/maxLength are ignored on a time field.`);
      } else if (format === "binary" || format === "byte" || s.contentEncoding === "binary") {
        f.kind = "file";
        readFileSettings(s, f, name, warnings);
      } else {
        if (format === "email") f.format = "email";
        else if (format === "uri" || format === "url") f.format = "url";
        else if (format) warnings.push(`${name}: format "${format}" is not supported — plain text.`);
        f.min = finite(s.minLength);
        f.max = finite(s.maxLength);
        if (typeof s[X_PREFIX] === "string" && s[X_PREFIX]) f.prefix = s[X_PREFIX];
        if (typeof s[X_SUFFIX] === "string" && s[X_SUFFIX]) f.suffix = s[X_SUFFIX];
      }
      break;
    }
    case "number":
    case "integer": {
      f.kind = "number";
      f.min = finite(s.minimum);
      f.max = finite(s.maximum);
      if (f.min === undefined && finite(s.exclusiveMinimum) !== undefined) {
        f.min = finite(s.exclusiveMinimum);
        warnings.push(`${name}: exclusiveMinimum is treated as the minimum.`);
      }
      if (f.max === undefined && finite(s.exclusiveMaximum) !== undefined) {
        f.max = finite(s.exclusiveMaximum);
        warnings.push(`${name}: exclusiveMaximum is treated as the maximum.`);
      }
      break;
    }
    case "boolean":
      f.kind = "boolean";
      break;
    case "array": {
      const items = isObj(s.items) ? s.items : {};
      const [first, second] = Array.isArray(s.prefixItems) ? s.prefixItems : [];
      if (isObj(first) && isObj(second) && isNumberNode(first) && isNumberNode(second)) {
        // A z.tuple of two numbers: the builder's range, each end's bound on its own item.
        f.kind = "range";
        f.min = finite(first.minimum);
        f.max = finite(second.maximum);
        rangeLengthWarning(name, s, warnings);
      } else if (items.format === "binary" || items.contentEncoding === "binary") {
        f.kind = "file";
        f.multiple = true;
        readFileSettings(s, f, name, warnings);
        readFileSettings(items, f, name, warnings);
        const minItems = finite(s.minItems);
        if (minItems !== undefined && !(minItems === 1 && f.required)) warnings.push(`${name}: minItems cannot be expressed in the builder — ignored.`);
      } else if (Array.isArray(items.enum) && items.enum.length) {
        f.kind = "multi";
        f.options = items.enum.map(asText);
        if (!items.enum.every((v) => typeof v === "string")) warnings.push(`${name}: non-text options were turned into text.`);
        // "at least one when required" is how the builder writes it; anything else is lost.
        const minItems = finite(s.minItems);
        if ((minItems !== undefined || finite(s.maxItems) !== undefined) && !(minItems === 1 && f.required)) {
          warnings.push(`${name}: minItems/maxItems cannot be expressed in the builder — ignored.`);
        }
      } else if (isNumberNode(items)) {
        // The older shape: one item schema for both numbers, carrying both bounds.
        f.kind = "range";
        f.min = finite(items.minimum);
        f.max = finite(items.maximum);
        rangeLengthWarning(name, s, warnings);
      } else {
        warnings.push(`${name}: a list without a fixed set of options — used a text field.`);
      }
      break;
    }
    case "object": {
      // Zod writes a date range as a plain object of two dates; older files also marked it with `format`.
      const props = isObj(s.properties) ? s.properties : {};
      if (s.format === "date-range" || (isDateNode(props.from) && isDateNode(props.to))) {
        f.kind = "date-range";
        for (const key of ["from", "to"] as const) {
          if (!isDateNode(props[key])) warnings.push(`${name}: the date range has no "${key}" date.`);
        }
      } else {
        warnings.push(`${name}: type "object" is not supported — used a text field.`);
      }
      break;
    }
    case undefined:
      warnings.push(`${name}: no "type" and no "enum" — used a text field.`);
      break;
    default:
      warnings.push(`${name}: type "${String(type)}" is not supported — used a text field.`);
  }

  if (f.kind !== "date-range" && (s.$ref || s.oneOf || s.anyOf || s.allOf || s.not || isObj(s.properties))) {
    warnings.push(`${name}: nested or composed schemas ($ref/oneOf/anyOf/allOf) are not resolved.`);
  }
  return f;
}

/**
 * `anyOf [<type>, { const: "" }]` (or a `null` branch) is how Zod writes a text
 * field that may be left empty; the value type is the other branch.
 */
function unwrapAnyOf(s: Json, name: string, warnings: string[]): { schema: Json; emptyAllowed: boolean } {
  const branches = Array.isArray(s.anyOf) ? s.anyOf.filter(isObj) : [];
  if (!branches.length) return { schema: s, emptyAllowed: false };
  const isEmpty = (b: Json) => b.const === "" || b.const === null || b.type === "null";
  const rest = branches.filter((b) => !isEmpty(b));
  const emptyAllowed = rest.length !== branches.length;
  if (rest.length > 1) {
    warnings.push(`${name}: anyOf with ${rest.length} alternatives is not supported — used a text field.`);
    return { schema: s, emptyAllowed };
  }
  if (!rest.length) {
    warnings.push(`${name}: anyOf holds no value type — used a text field.`);
    return { schema: s, emptyAllowed };
  }
  const merged: Json = { ...s, ...rest[0] };
  delete merged.anyOf;
  return { schema: merged, emptyAllowed };
}

/** File settings: the builder's own `x-` keys, with a byte `maxLength` as a fallback for other files. */
function readFileSettings(node: Json, f: FieldSpec, name: string, warnings: string[]): void {
  if (typeof node[X_ACCEPT] === "string" && node[X_ACCEPT]) f.accept = node[X_ACCEPT];
  const mb = finite(node[X_MAX_SIZE_MB]);
  if (mb !== undefined) {
    f.maxSizeMb = mb;
  } else {
    const bytes = finite(node.maxLength);
    if (bytes !== undefined) {
      const size = Math.round((bytes / (1024 * 1024)) * 100) / 100;
      if (size >= 0.1 && Math.round(size * 1024 * 1024) === bytes) f.maxSizeMb = size;
      else warnings.push(`${name}: maxLength ${bytes} is not a size in megabytes — ignored.`);
    }
  }
  if (typeof node[X_MULTIPLE] === "boolean") f.multiple = node[X_MULTIPLE];
}

/** The `errorMessage` keyword: ajv-errors keeps the keyword keys, a bare string is the required message. */
function readErrorMessages(v: unknown): Record<string, string> | undefined {
  if (typeof v === "string") return v ? { type: v } : undefined;
  if (!isObj(v)) return undefined;
  const out: Record<string, string> = {};
  for (const [keyword, message] of Object.entries(v)) if (typeof message === "string" && message) out[keyword] = message;
  return Object.keys(out).length ? out : undefined;
}

/** A range is exactly two numbers; any other length cannot be expressed in the builder. */
function rangeLengthWarning(name: string, s: Json, warnings: string[]): void {
  const minItems = finite(s.minItems);
  const maxItems = finite(s.maxItems);
  if (minItems !== undefined && minItems !== 2) warnings.push(`${name}: only a two-number range is supported — minItems is ignored.`);
  if (maxItems !== undefined && maxItems !== 2) warnings.push(`${name}: only a two-number range is supported — maxItems is ignored.`);
}

function isNumberNode(n: Json): boolean {
  return n.type === "number" || n.type === "integer";
}

function isDateNode(n: unknown): boolean {
  return isObj(n) && n.type === "string" && (n.format === "date" || n.format === "date-time");
}

/** `ui:order` decides the field order; names missing from it keep their schema order. */
function applyOrder(fields: FieldSpec[], order: unknown, warnings: string[]): FieldSpec[] {
  if (!Array.isArray(order)) return fields;
  const rest: Record<string, FieldSpec> = Object.fromEntries(fields.map((f) => [f.name, f]));
  const ordered: FieldSpec[] = [];
  for (const name of order) {
    if (typeof name !== "string") continue;
    const f = rest[name];
    if (!f) {
      warnings.push(`ui:order lists "${name}", which is not a field.`);
      continue;
    }
    ordered.push(f);
    delete rest[name];
  }
  return [...ordered, ...Object.values(rest)];
}

/** `ui:widget` per field → the builder's override map, keyed by the regenerated field ids. */
function readOverrides(uiSchema: Json, fields: FieldSpec[], warnings: string[]): Record<string, string> {
  const byName: Record<string, FieldSpec> = Object.fromEntries(fields.map((f) => [f.name, f]));
  const out: Record<string, string> = {};
  for (const [name, entry] of Object.entries(uiSchema)) {
    if (name === UI_ORDER) continue;
    const widget = isObj(entry) && typeof entry[UI_WIDGET] === "string" ? entry[UI_WIDGET] : undefined;
    if (!widget) continue;
    const f = byName[name];
    if (!f) {
      warnings.push(`ui:widget is set for "${name}", which is not a field.`);
      continue;
    }
    if (!candidatesFor(f.kind).some((c) => c.id === widget)) {
      warnings.push(`"${name}": ui:widget "${widget}" cannot hold a ${f.kind} value — ignored.`);
      continue;
    }
    out[f.id] = widget;
  }
  return out;
}

