const ZOD_HINT = "Paste Zod source containing a z.object({ … }) literal.";

const SIMPLE_ESCAPES: Record<string, string> = { n: "\n", t: "\t", r: "\r", b: "\b", f: "\f", v: "\v", "0": "\0" };

function unescapeLiteral(lit: string): string {
  return lit
    .slice(1, -1)
    .replace(/\\(u[0-9a-fA-F]{4}|x[0-9a-fA-F]{2}|[\s\S])/g, (_, esc: string) =>
      esc.length > 1 ? String.fromCharCode(parseInt(esc.slice(1), 16)) : (SIMPLE_ESCAPES[esc] ?? esc),
    );
}

/** The quoted literal that starts at `i`, escapes included. Comments are already stripped. */
function readStringAt(src: string, i: number): string {
  const quote = src[i];
  let out = quote;
  for (let j = i + 1; j < src.length; j++) {
    out += src[j];
    if (src[j] === "\\") {
      out += src[++j] ?? "";
      continue;
    }
    if (src[j] === quote) break;
  }
  return out;
}

function stripComments(src: string): string {
  let out = "";
  for (let i = 0; i < src.length; ) {
    const c = src[i];
    if (c === '"' || c === "'" || c === "`") {
      const lit = readStringAt(src, i);
      out += lit;
      i += lit.length;
      continue;
    }
    if (c === "/" && src[i + 1] === "/") {
      while (i < src.length && src[i] !== "\n") i++;
      continue;
    }
    if (c === "/" && src[i + 1] === "*") {
      i += 2;
      while (i < src.length && !(src[i] === "*" && src[i + 1] === "/")) i++;
      i += 2;
      continue;
    }
    out += c;
    i++;
  }
  return out;
}

/** Index of the `}` matching the `{` at `open`, or -1. */
function matchBrace(src: string, open: number): number {
  return matchDelimiter(src, open, "{", "}");
}

/** Index of the delimiter matching the opening one at `open`, or -1. Ignores strings. */
function matchDelimiter(src: string, open: number, openCh: string, closeCh: string): number {
  let depth = 0;
  for (let i = open; i < src.length; ) {
    const c = src[i];
    if (c === '"' || c === "'" || c === "`") {
      const lit = readStringAt(src, i);
      i += lit.length;
      continue;
    }
    if (c === openCh) depth++;
    else if (c === closeCh && --depth === 0) return i;
    i++;
  }
  return -1;
}

/** Splits an object body on commas at depth 0, and on newlines that are not a `.method(…)` continuation. */
function splitEntries(body: string): string[] {
  const out: string[] = [];
  const open: string[] = [];
  let buf = "";
  for (let i = 0; i < body.length; ) {
    const c = body[i];
    if (c === '"' || c === "'" || c === "`") {
      const lit = readStringAt(body, i);
      buf += lit;
      i += lit.length;
      continue;
    }
    if (c === "{" || c === "(" || c === "[") open.push(c);
    else if (c === "}" || c === ")" || c === "]") open.pop();
    else if (!open.length && (c === "," || c === "\n")) {
      const rest = body.slice(i + 1);
      if (c === "\n" && rest.trimStart().startsWith(".")) {
        buf += c;
        i++;
        continue;
      }
      out.push(buf);
      buf = "";
      i++;
      continue;
    }
    buf += c;
    i++;
  }
  out.push(buf);
  return out.map((e) => e.trim()).filter(Boolean);
}

/** Index of `ch` at depth 0, or -1. */
function indexOfTopLevel(text: string, ch: string): number {
  const open: string[] = [];
  for (let i = 0; i < text.length; ) {
    const c = text[i];
    if (c === '"' || c === "'" || c === "`") {
      const lit = readStringAt(text, i);
      i += lit.length;
      continue;
    }
    if (c === "{" || c === "(" || c === "[") open.push(c);
    else if (c === "}" || c === ")" || c === "]") open.pop();
    else if (!open.length && c === ch) return i;
    i++;
  }
  return -1;
}

const DESCRIBE_RE = /\.\s*describe\s*\(\s*("(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'|`(?:\\.|[^`\\])*`)\s*\)/;

/** The first `.describe("…")` string in an expression, if any. */
function matchDescribe(expr: string): string | undefined {
  const m = DESCRIBE_RE.exec(expr);
  return m ? unescapeLiteral(m[1]) : undefined;
}

/** The string options of the first `z.enum([ … ])` in the expression, or null. */
function zodEnumOptions(expr: string): string[] | null {
  const at = expr.search(/z\s*\.\s*enum\s*\(/);
  if (at < 0) return null;
  const open = expr.indexOf("[", at);
  if (open < 0) return null;
  const options: string[] = [];
  for (let i = open + 1; i < expr.length; ) {
    const c = expr[i];
    if (c === "]") break;
    if (c === '"' || c === "'" || c === "`") {
      const lit = readStringAt(expr, i);
      options.push(unescapeLiteral(lit));
      i += lit.length;
      continue;
    }
    i++;
  }
  return options.length ? options : null;
}

const ZOD_OPTIONAL_RE = /\.\s*optional\s*\(\s*\)|\.\s*nullable\s*\(\s*\)|\.\s*or\s*\(\s*z\s*\.\s*literal\s*\(\s*(?:""|''|``)\s*\)\s*\)/;

// The base type is what the expression *starts* with; a later `.url()` or
// `.or(z.literal(""))` only tunes it, so these must stay anchored.
// KINDS: add new kinds here (time, date-range, range, file).
const ZOD_ARRAY = /^z\s*\.\s*array\s*\(/;
const ZOD_ENUM = /^z\s*\.\s*enum\s*\(/;
const ZOD_LITERAL = /^z\s*\.\s*literal\s*\(\s*("(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'|`(?:\\.|[^`\\])*`)\s*\)/;
const ZOD_STRING = /^z\s*\.\s*(?:string|coerce\s*\.\s*string)\s*\(/;
const ZOD_EMAIL = /^z\s*\.\s*email\s*\(/;
const ZOD_URL = /^z\s*\.\s*url\s*\(/;
const ZOD_DATE = /^z\s*\.\s*(?:date|iso\s*\.\s*(?:date|datetime))\s*\(/;
const ZOD_NUMBER = /^z\s*\.\s*(?:number|int|coerce\s*\.\s*(?:number|int))\s*\(/;
const ZOD_BOOLEAN = /^z\s*\.\s*(?:boolean|coerce\s*\.\s*boolean)\s*\(/;
const ZOD_FILE = /^z\s*\.\s*file\s*\(/;
const ZOD_TUPLE = /^z\s*\.\s*tuple\s*\(/;
const ZOD_OBJECT = /^z\s*\.\s*object\s*\(/;

type ZodCall = { name: string; args: string; text: string };

/**
 * `z.string().min(1, "msg").max(3)` → the base `z.string()` and its trailing `.method(args)` calls.
 * The base is the *first* call (`z.string(…)`, `z.coerce.number(…)`, `z.iso.date(…)`), so
 * `z.coerce.number().min(0)` keeps `coerce` inside the base.
 */
function zodChain(expr: string): { base: string; calls: ZodCall[] } {
  let i = 0;
  while (i < expr.length && !/[A-Za-z0-9_$]/.test(expr[i])) i++;
  while (i < expr.length && /[A-Za-z0-9_$]/.test(expr[i])) i++;
  for (;;) {
    let j = i;
    while (j < expr.length && /\s/.test(expr[j])) j++;
    if (expr[j] !== ".") break;
    j++;
    while (j < expr.length && /\s/.test(expr[j])) j++;
    const nameAt = j;
    while (j < expr.length && /[A-Za-z0-9_$]/.test(expr[j])) j++;
    if (j === nameAt) break;
    let k = j;
    while (k < expr.length && /\s/.test(expr[k])) k++;
    if (expr[k] === "(") {
      const close = matchDelimiter(expr, k, "(", ")");
      // The base ends after its first parenthesised call.
      i = close < 0 ? expr.length : close + 1;
      break;
    }
    i = j; // `.coerce` / `.iso`: another segment before the call that ends the base
  }
  const calls: ZodCall[] = [];
  for (let at = i; at < expr.length; ) {
    while (at < expr.length && /\s/.test(expr[at])) at++;
    if (expr[at] !== ".") break;
    let j = at + 1;
    while (j < expr.length && /[A-Za-z0-9_$]/.test(expr[j])) j++;
    const name = expr.slice(at + 1, j);
    while (j < expr.length && /\s/.test(expr[j])) j++;
    if (expr[j] !== "(") break;
    const close = matchDelimiter(expr, j, "(", ")");
    if (close < 0) break;
    calls.push({ name, args: expr.slice(j + 1, close), text: expr.slice(at, close + 1) });
    at = close + 1;
  }
  return { base: expr.slice(0, i).trim(), calls };
}

/** The arguments inside the outermost `( … )` of an expression, or "". */
function outerArgs(text: string): string {
  const open = text.indexOf("(");
  const close = open < 0 ? -1 : matchDelimiter(text, open, "(", ")");
  return close < 0 ? "" : text.slice(open + 1, close);
}

/** The hand-written message in a call's arguments: a trailing string, or `{ error: "…" }`. */
function messageLiteral(args: string): string | undefined {
  const parts = splitEntries(args);
  const last = parts[parts.length - 1]?.trim();
  if (!last) return undefined;
  const bare = /^("(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'|`(?:\\.|[^`\\])*`)$/.exec(last);
  if (bare) return unescapeLiteral(bare[1]);
  const named = /(?:^|[,{]\s*)(?:error|message)\s*:\s*("(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'|`(?:\\.|[^`\\])*`)/.exec(last);
  return named ? unescapeLiteral(named[1]) : undefined;
}

/** The source of a `/…/flags` literal argument, for recognising the builder's own patterns. */
function regexSource(args: string): string | undefined {
  const m = /^\s*\/((?:\\.|[^/\\])*)\/[a-z]*/.exec(args);
  return m ? m[1] : undefined;
}

/** Bytes → megabytes, when that is a size the builder can express. */
function bytesToMb(bytes: number | undefined): number | undefined {
  if (bytes === undefined || bytes <= 0) return undefined;
  const size = Math.round((bytes / (1024 * 1024)) * 100) / 100;
  return size >= 0.1 && Math.round(size * 1024 * 1024) === bytes ? size : undefined;
}

/**
 * One `key: <expr>` entry → a field. What the builder has a shape for is read out;
 * every other call (`.refine(…)`, `.transform(…)`, a `.regex(…)` it does not know)
 * is kept verbatim in `customZod` — text, never executed here.
 */
function mapZodValue(key: string, expr: string, i: number, warnings: string[]): FieldSpec {
  const { base, calls } = zodChain(expr);
  const f: FieldSpec = { id: `imp_${i + 1}`, name: key, label: prettify(key), kind: "string", required: !ZOD_OPTIONAL_RE.test(expr) };
  const described = matchDescribe(expr);
  if (described) f.description = described;

  const used = new Set(["optional", "nullable", "describe"]);
  // `.or(z.literal(""))` is the builder's own "may be left empty", not custom code.
  if (calls.some((c) => c.name === "or" && /^\s*z\s*\.\s*literal\s*\(\s*(?:""|''|``)\s*\)\s*$/.test(c.args))) used.add("or");
  const messages: Record<string, string> = {};
  const note = (keyword: string, message: string | undefined) => {
    if (message) messages[keyword] = message;
  };
  const call = (name: string) => calls.find((c) => c.name === name);
  const numberArgOf = (name: string) => {
    const m = /^\s*(-?\d+(?:\.\d+)?)/.exec(call(name)?.args ?? "");
    return m ? Number(m[1]) : undefined;
  };

  const item = ZOD_ARRAY.test(base) ? outerArgs(base).trim() : "";
  const itemChain = item ? zodChain(item) : { base: "", calls: [] as ZodCall[] };
  const baseArg = outerArgs(base);

  if (item) {
    // Several of something: a list of options, or several files.
    if (ZOD_ENUM.test(itemChain.base)) {
      const options = zodEnumOptions(itemChain.base);
      if (options) {
        f.kind = "multi";
        f.options = options;
      } else {
        warnings.push(`${key}: a z.enum(…) without readable string options — used a text field.`);
      }
    } else if (ZOD_STRING.test(itemChain.base)) {
      f.kind = "multi";
    } else if (ZOD_FILE.test(itemChain.base)) {
      f.kind = "file";
      f.multiple = true;
      for (const c of itemChain.calls) if (c.name === "max") used.add("max");
      f.maxSizeMb = bytesToMb(Number(/^\s*(\d+)/.exec(itemChain.calls.find((c) => c.name === "max")?.args ?? "")?.[1]));
      note("maxLength", messageLiteral(itemChain.calls.find((c) => c.name === "max")?.args ?? ""));
    } else {
      warnings.push(`${key}: an array of something else — used a text field.`);
    }
    if (f.kind === "multi" || f.kind === "file") {
      used.add("min");
      note("minItems", messageLiteral(call("min")?.args ?? ""));
    }
  } else if (ZOD_ENUM.test(base)) {
    const options = zodEnumOptions(base);
    if (options) {
      f.kind = "enum";
      f.options = options;
    } else {
      warnings.push(`${key}: a z.enum(…) without readable string options — used a text field.`);
    }
    note("enum", messageLiteral(baseArg));
  } else if (ZOD_LITERAL.test(base)) {
    const literal = ZOD_LITERAL.exec(base);
    f.kind = "enum";
    if (literal) f.options = [unescapeLiteral(literal[1])];
  } else if (ZOD_STRING.test(base)) {
    if (call("email")) {
      used.add("email");
      f.format = "email";
      note("format", messageLiteral(call("email")?.args ?? ""));
    } else if (call("url")) {
      used.add("url");
      f.format = "url";
      note("format", messageLiteral(call("url")?.args ?? ""));
    }
    const time = calls.find((c) => c.name === "regex" && regexSource(c.args) === TIME_PATTERN);
    if (time) {
      used.add("regex");
      f.kind = "time";
      note("pattern", messageLiteral(time.args));
    } else if (!f.format) {
      used.add("min").add("max");
      // A required string is at least one character anyway, so `.min(1)` adds nothing.
      const min = numberArgOf("min");
      f.min = f.required && min === 1 ? undefined : min;
      f.max = numberArgOf("max");
      note("minLength", messageLiteral(call("min")?.args ?? ""));
      note("maxLength", messageLiteral(call("max")?.args ?? ""));
    }
  } else if (ZOD_EMAIL.test(base)) {
    f.format = "email";
    note("format", messageLiteral(baseArg));
  } else if (ZOD_URL.test(base)) {
    f.format = "url";
    note("format", messageLiteral(baseArg));
  } else if (ZOD_DATE.test(base)) {
    f.kind = "date";
    used.add("min").add("max"); // `.min()` on a date is a date bound the builder cannot hold
  } else if (ZOD_NUMBER.test(base)) {
    f.kind = "number";
    used.add("min").add("max");
    f.min = numberArgOf("min");
    f.max = numberArgOf("max");
    note("type", messageLiteral(baseArg));
    note("minimum", messageLiteral(call("min")?.args ?? ""));
    note("maximum", messageLiteral(call("max")?.args ?? ""));
  } else if (ZOD_BOOLEAN.test(base)) {
    f.kind = "boolean";
  } else if (ZOD_FILE.test(base)) {
    f.kind = "file";
    used.add("max");
    f.maxSizeMb = bytesToMb(Number(/^\s*(\d+)/.exec(call("max")?.args ?? "")?.[1]));
    note("type", messageLiteral(baseArg));
    note("maxLength", messageLiteral(call("max")?.args ?? ""));
  } else if (ZOD_TUPLE.test(base)) {
    f.kind = "range";
    const refine = call("refine");
    if (refine) {
      used.add("refine");
      // The builder's own bounds sit in the refine: `a >= min && b <= max && a <= b`.
      f.min = Number(/[\w\]]\s*>=\s*(-?\d+(?:\.\d+)?)/.exec(refine.args)?.[1]);
      f.max = Number(/[\w\]]\s*<=\s*(-?\d+(?:\.\d+)?)/.exec(refine.args)?.[1]);
      if (!Number.isFinite(f.min)) f.min = undefined;
      if (!Number.isFinite(f.max)) f.max = undefined;
      note("minimum", messageLiteral(refine.args));
    }
  } else if (ZOD_OBJECT.test(base) && /\bfrom\s*:/.test(baseArg) && /\bto\s*:/.test(baseArg)) {
    f.kind = "date-range";
  } else {
    warnings.push(`${key}: unsupported Zod type "${expr.replace(/\s+/g, " ").slice(0, 60)}" — used a text field.`);
  }

  const custom = [...calls, ...itemChain.calls].filter((c) => !used.has(c.name)).map((c) => c.text).join("");
  if (custom) f.customZod = custom;
  for (const [keyword, message] of Object.entries(messages)) {
    if (message !== defaultMessage(f, keyword)) f.errorMessage = { ...(f.errorMessage ?? {}), [keyword]: message };
  }
  return f;
}

export function parseZod(source: string): ImportResult {
  const warnings: string[] = [];
  const base = { format: "zod" as const, purpose: "", fields: [] as FieldSpec[], warnings };
  const src = stripComments(source);
  const objectAt = src.search(/z\s*\.\s*object\s*\(/);
  if (objectAt < 0) return { ...base, ok: false, warnings: [`No z.object({ … }) found. ${ZOD_HINT}`] };
  const braceAt = src.indexOf("{", src.indexOf("(", objectAt));
  if (braceAt < 0) return { ...base, ok: false, warnings: [`z.object( has no { … } body. ${ZOD_HINT}`] };
  const end = matchBrace(src, braceAt);
  if (end < 0) return { ...base, ok: false, warnings: ["Unbalanced braces in the z.object({ … }) body."] };

  const fields: FieldSpec[] = [];
  for (const entry of splitEntries(src.slice(braceAt + 1, end))) {
    const colon = indexOfTopLevel(entry, ":");
    const key = colon < 0 ? "" : entry.slice(0, colon).trim().replace(/^["'`]|["'`]$/g, "");
    if (!key) {
      warnings.push(`Skipped "${entry.replace(/\s+/g, " ").slice(0, 40)}": it is not a key: value pair.`);
      continue;
    }
    fields.push(normalizeField(mapZodValue(key, entry.slice(colon + 1).trim(), fields.length, warnings)));
  }
  if (!fields.length) warnings.push("No fields found in the object.");
  return { ...base, ok: fields.length > 0, purpose: matchDescribe(src.slice(end + 1)) ?? "", fields, warnings };
}

