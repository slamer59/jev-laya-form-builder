/**
 * Paste-to-form conversion, and the builder's own file format.
 *
 * The document is JSON Schema draft 2020-12 plus an RJSF-style uiSchema, and the
 * same one is used in a downloaded file, in the URL hash and in localStorage:
 *
 *   { "schema": { "type": "object", "properties": { … } }, "uiSchema": { … } }
 *
 * The schema is **generated by Zod**, not written by hand: `shared/schema.ts`
 * builds the very schema the preview validates with, carrying the builder's
 * settings as `.meta()` — purpose as the object's `description`, label/hint as a
 * field's `title`/`description`, and the settings JSON Schema has no place for as
 * `x-` extensions (`x-threshold`, `x-prefix`, `x-suffix`, `x-accept`,
 * `x-maxSizeMb`, `x-multiple`). `formDocument` then calls `z.toJSONSchema` and
 * repairs the few shapes Zod cannot express (`fixShapes`). The uiSchema is the
 * only hand-built object, and it is not JSON Schema: `ui:widget` and `ui:order`.
 *
 * Reading is lenient and hand-written — Zod cannot produce a `FieldSpec`. Any
 * JSON Schema object works, and everything the builder cannot express becomes a
 * text field with an entry in `warnings`.
 */

export type FormDocument = { schema: Record<string, unknown>; uiSchema: Record<string, unknown> };

export type ImportFormat = "builder-file" | "json-schema" | "zod";

export type ImportResult = {
  ok: boolean;
  format: ImportFormat;
  purpose: string;
  fields: FieldSpec[];
  /** Builder files only, and only when the file carries it. */
  threshold?: number;
  overrides?: Record<string, string>;
  warnings: string[];
};

type Json = Record<string, unknown>;

const isObj = (v: unknown): v is Json => !!v && typeof v === "object" && !Array.isArray(v);
const finite = (v: unknown) => (typeof v === "number" && Number.isFinite(v) ? v : undefined);
const asText = (v: unknown) => (typeof v === "string" ? v : JSON.stringify(v));

/** `full_name` / `fullName` → `Full name`, the label used when the schema has no title. */
function prettify(key: string): string {
  const words = key
    .replace(/[_\-.]+/g, " ")
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .trim();
  return words ? words[0].toUpperCase() + words.slice(1) : key;
}

/* ------------------------------------------------------------------ writing */

export function formDocument(s: SavedForm): FormDocument {
  const form = normalizeForm(s);
  const byName: Record<string, FieldSpec | undefined> = Object.fromEntries(form.fields.map((f) => [f.name, f]));
  const schema = z.toJSONSchema(buildSchema(form.fields, { purpose: form.purpose, threshold: form.threshold }), {
    // `draft-2020-12` is what the builder's own documents declare; "any" turns
    // the bits Zod cannot express (z.date(), fully covered by `fixShapes`) into
    // `{}` instead of throwing, so one odd field never blocks an export.
    target: "draft-2020-12",
    unrepresentable: "any",
    override: ({ jsonSchema, path }) => fixShapes(jsonSchema, path, byName, form),
  });
  const uiSchema: Json = {};
  for (const f of form.fields) if (form.overrides[f.id]) uiSchema[f.name] = { [UI_WIDGET]: form.overrides[f.id] };
  uiSchema[UI_ORDER] = form.fields.map((f) => f.name);
  return { schema, uiSchema };
}

/**
 * The JSON Schema `z.toJSONSchema` cannot produce on its own. Every branch here
 * repairs a node Zod already generated — there is no second serializer:
 *
 *   date / date-range   z.date() has no JSON Schema form (`{}`)          → format: date
 *   time                only a regex pattern survived                    → format: time, pattern dropped
 *   required boolean    the `.refine(v => v)` "must be ticked" is lost   → const: true
 *   range               the tuple's bounds live in `.refine`             → minimum/maximum on prefixItems
 *   file                the size limit became a byte `maxLength`         → dropped, x-maxSizeMb carries it
 *   email               Zod also emits a long regex                      → pattern dropped
 *   required string     Zod always emits minLength: 1                    → dropped unless the field sets a minimum
 *   required            Zod keeps empty-allowed strings in `required`    → exactly the builder's required fields
 */
function fixShapes(node: Json, path: (string | number)[], byName: Record<string, FieldSpec | undefined>, form: SavedForm): void {
  if (!path.length) {
    const required = form.fields.filter((f) => f.required).map((f) => f.name);
    if (required.length) node.required = required;
    else delete node.required;
    return;
  }
  if (path[0] !== "properties") return;
  const f = byName[String(path[1])];
  if (!f) return;
  const nested = path.length > 2; // a node inside the field, e.g. a date range's from/to
  // A branch that only allows "empty" (`const: ""`) is not the field itself.
  if (nested && node.const !== undefined) return;
  // Zod keys its enum output by value, so options like "0" would come first; the builder's order wins.
  if (Array.isArray(node.enum) && f.options?.length) node.enum = [...f.options];

  switch (f.kind) {
    case "date":
      // A union node is only a wrapper; the branch inside carries the type.
      if (!Array.isArray(node.anyOf)) {
        node.type = "string";
        node.format = "date";
      }
      break;
    case "date-range":
      if (nested) {
        node.type = "string";
        node.format = "date";
      }
      break;
    case "time":
      if (!Array.isArray(node.anyOf)) {
        node.type = "string";
        node.format = "time";
        delete node.pattern;
      }
      break;
    case "string":
      // Zod also emits a long regex for format: email; it adds nothing to the meaning.
      if (node.format === "email") delete node.pattern;
      // Zod always emits minLength: 1 for a required string; the builder's "required" covers that.
      if (!nested && !node.format && !Array.isArray(node.anyOf) && f.required && (f.min == null || f.min < 1) && node.minLength === 1) delete node.minLength;
      break;
    case "boolean":
      if (!nested && f.required) node.const = true;
      break;
    case "range":
      if (!nested && Array.isArray(node.prefixItems)) {
        const [first, second] = node.prefixItems;
        if (isObj(first) && f.min != null) first.minimum = f.min;
        if (isObj(second) && f.max != null) second.maximum = f.max;
      }
      break;
    case "file":
      delete node.maxLength; // bytes; the builder stores megabytes as x-maxSizeMb
      break;
  }
}

export const formToJson = (s: SavedForm) => JSON.stringify(formDocument(s), null, 2);

